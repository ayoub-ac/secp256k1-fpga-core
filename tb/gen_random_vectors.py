"""Generate random secp256k1 ECDSA test vectors for the C++ harness.

Output: a C++ header (random_vectors.h) defining static tables of
{d, qx, qy} key-derivation cases and {qx, qy, h, r, s, accept} verify
cases. The harness in sim_main.cpp includes this header and runs each
through the DUT.

Strategy:
  * 60 random key-derivation pairs (d -> Q = d*G).
  * 50 random valid sign-then-verify rounds: privkey, hash, nonce,
    output (r, s) computed by Python `coincurve` (which uses libsecp256k1
    under the hood; signatures are RFC 6979 deterministic). Each is
    verified with the DUT and expected to accept.
  * 20 tampered-signature cases: take a valid (r, s), flip a bit,
    expect verify -> reject.

We use coincurve.PrivateKey().sign_recoverable() and the underlying
ecdsa_serialize APIs to extract the (r, s) pair without DER/PEM wrapping.

Run: `python3 tb/gen_random_vectors.py > tb/random_vectors.h`
(invoked by `make regen_vectors`). Deterministic given the seed.
"""

import hashlib
import random
import sys

import coincurve
from coincurve.utils import int_to_bytes_padded


SECP256K1_N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141


def privkey_int(d_bytes: bytes) -> int:
    return int.from_bytes(d_bytes, "big")


def derive_pubkey(d_bytes: bytes) -> tuple[bytes, bytes]:
    pk = coincurve.PrivateKey(d_bytes)
    pub_uncompressed = pk.public_key.format(compressed=False)
    # 0x04 || X (32) || Y (32)
    return pub_uncompressed[1:33], pub_uncompressed[33:65]


def sign_rs(d_bytes: bytes, h_bytes: bytes) -> tuple[bytes, bytes]:
    """Sign the 32-byte hash and return (r, s) as 32-byte big-endian.

    coincurve.PrivateKey.sign uses RFC 6979 deterministic nonces.
    The wire format is DER; we use sign_recoverable() and parse the
    raw 64-byte (r,s) prefix.
    """
    pk = coincurve.PrivateKey(d_bytes)
    sig = pk.sign_recoverable(h_bytes, hasher=None)
    # 65 bytes: r (32) || s (32) || rec_id (1)
    r = sig[0:32]
    s = sig[32:64]
    # Coincurve enforces low-S already.
    return r, s


def verify_rs(qx: bytes, qy: bytes, h_bytes: bytes, r: bytes, s: bytes) -> bool:
    pub_uncompressed = b"\x04" + qx + qy
    try:
        pubkey = coincurve.PublicKey(pub_uncompressed)
    except ValueError:
        return False
    # coincurve accepts DER signatures; build minimal DER.
    der = build_der(int.from_bytes(r, "big"), int.from_bytes(s, "big"))
    if der is None:
        return False
    try:
        return pubkey.verify(der, h_bytes, hasher=None)
    except Exception:
        return False


def build_der(r: int, s: int) -> bytes | None:
    if r == 0 or s == 0:
        return None

    def encode_int(x: int) -> bytes:
        b = x.to_bytes((x.bit_length() + 7) // 8, "big")
        if b[0] & 0x80:
            b = b"\x00" + b
        return b"\x02" + bytes([len(b)]) + b

    body = encode_int(r) + encode_int(s)
    return b"\x30" + bytes([len(body)]) + body


def hexstr(b: bytes) -> str:
    return b.hex()


def emit_array(out, name: str, blob: bytes) -> None:
    out.write(f"static const uint8_t {name}[] = {{\n")
    for i in range(0, len(blob), 16):
        chunk = blob[i:i + 16]
        out.write("    " + ", ".join(f"0x{c:02x}" for c in chunk) + ",\n")
    out.write("};\n\n")


def main() -> int:
    random.seed(0xDEADC0DE_C0FFEE_42)

    out = sys.stdout
    out.write("// SPDX-License-Identifier: GPL-3.0-or-later OR Commercial\n")
    out.write("// AUTO-GENERATED by tb/gen_random_vectors.py.\n")
    out.write("// Do not edit by hand; regenerate with `make regen_vectors`.\n")
    out.write("#pragma once\n")
    out.write("#include <cstdint>\n")
    out.write("#include <cstddef>\n\n")

    out.write("struct KeyDeriveVec {\n")
    out.write("    const uint8_t* d;       // 32 B private key (big-endian)\n")
    out.write("    const uint8_t* qx;      // 32 B X coord of Q = d*G\n")
    out.write("    const uint8_t* qy;      // 32 B Y coord of Q = d*G\n")
    out.write("};\n\n")

    out.write("struct VerifyVec {\n")
    out.write("    const uint8_t* qx;      // 32 B\n")
    out.write("    const uint8_t* qy;      // 32 B\n")
    out.write("    const uint8_t* h;       // 32 B\n")
    out.write("    const uint8_t* r;       // 32 B\n")
    out.write("    const uint8_t* s;       // 32 B\n")
    out.write("    uint8_t        accept;  // 0 or 1\n")
    out.write("};\n\n")

    out.write("struct SignVec {\n")
    out.write("    const uint8_t* d;       // 32 B private key\n")
    out.write("    const uint8_t* h;       // 32 B hash\n")
    out.write("    const uint8_t* k;       // 32 B per-signature nonce\n")
    out.write("    const uint8_t* r;       // 32 B expected r (low-S form)\n")
    out.write("    const uint8_t* s;       // 32 B expected s (low-S form)\n")
    out.write("};\n\n")

    arena = bytearray()
    kd_table = []
    vf_table = []

    # ---- 60 key-derivation cases ---------------------------------------
    for i in range(60):
        # Stay safely below n.
        d_int = random.randint(1, SECP256K1_N - 1)
        d = d_int.to_bytes(32, "big")
        qx, qy = derive_pubkey(d)
        offs = []
        for blob in (d, qx, qy):
            offs.append(len(arena))
            arena.extend(blob)
        kd_table.append(offs)

    # ---- 70 valid verify cases (accept=1) ------------------------------
    sign_table = []                                 # for the sign tests
    valid_count = 0
    while valid_count < 70:
        d_int = random.randint(1, SECP256K1_N - 1)
        d = d_int.to_bytes(32, "big")
        h = random.randbytes(32)
        try:
            r, s = sign_rs(d, h)
        except Exception:
            continue
        qx, qy = derive_pubkey(d)
        if not verify_rs(qx, qy, h, r, s):
            continue
        offs = []
        for blob in (qx, qy, h, r, s):
            offs.append(len(arena))
            arena.extend(blob)
        vf_table.append((offs, 1))
        valid_count += 1

    # ---- 20 tampered cases (accept=0) ----------------------------------
    tampered_count = 0
    while tampered_count < 20:
        d_int = random.randint(1, SECP256K1_N - 1)
        d = d_int.to_bytes(32, "big")
        h = random.randbytes(32)
        try:
            r, s = sign_rs(d, h)
        except Exception:
            continue
        qx, qy = derive_pubkey(d)
        # Flip a random bit in r OR s.
        target = bytearray(r if random.random() < 0.5 else s)
        bit = random.randint(0, 255)
        target[bit // 8] ^= 1 << (bit % 8)
        if random.random() < 0.5:
            r2, s2 = bytes(target), s
        else:
            r2, s2 = r, bytes(target)
        # Make sure tampered version really fails.
        if verify_rs(qx, qy, h, r2, s2):
            continue
        offs = []
        for blob in (qx, qy, h, r2, s2):
            offs.append(len(arena))
            arena.extend(blob)
        vf_table.append((offs, 0))
        tampered_count += 1

    # ---- 30 sign cases (callers passes the same RFC 6979 nonce) --------
    # We need the underlying nonce that coincurve / libsecp256k1 uses for
    # sign(). RFC 6979 is deterministic from (d, h). Because libsecp256k1
    # does not expose the nonce explicitly, we replicate the algorithm
    # in pure Python and verify it matches by independently signing with
    # this k via the (k * G) -> r path and the s = k^-1 * (h + r*d) (mod n)
    # formula, then comparing against coincurve's signature.
    sign_count = 0
    tries = 0
    while sign_count < 30 and tries < 2000:
        tries += 1
        d_int = random.randint(1, SECP256K1_N - 1)
        d = d_int.to_bytes(32, "big")
        h = random.randbytes(32)
        h_int = int.from_bytes(h, "big") % SECP256K1_N

        k_int = rfc6979_k(d_int, int.from_bytes(h, "big"))
        k = k_int.to_bytes(32, "big")
        # Compute (r, s) ourselves to confirm.
        r_calc, s_calc = sign_with_explicit_k(d_int, h_int, k_int)
        if r_calc == 0 or s_calc == 0:
            continue
        # Cross-check with coincurve's deterministic signature.
        r_cc, s_cc = sign_rs(d, h)
        # Coincurve enforces low-S; replicate.
        if s_calc > SECP256K1_N // 2:
            s_calc = SECP256K1_N - s_calc
        r_calc_b = r_calc.to_bytes(32, "big")
        s_calc_b = s_calc.to_bytes(32, "big")
        if r_calc_b != r_cc or s_calc_b != s_cc:
            # Should not happen if RFC 6979 is implemented correctly.
            continue
        offs = []
        for blob in (d, h, k, r_calc_b, s_calc_b):
            offs.append(len(arena))
            arena.extend(blob)
        sign_table.append(offs)
        sign_count += 1

    arena.append(0)

    out.write("static const uint8_t kSecArena[] = {\n")
    for i in range(0, len(arena), 16):
        chunk = arena[i:i + 16]
        out.write("    " + ", ".join(f"0x{c:02x}" for c in chunk) + ",\n")
    out.write("};\n\n")

    out.write("static const KeyDeriveVec kKeyDeriveVecs[] = {\n")
    for offs in kd_table:
        d_off, qx_off, qy_off = offs
        out.write(f"    {{ kSecArena + {d_off}, kSecArena + {qx_off}, "
                  f"kSecArena + {qy_off} }},\n")
    out.write("};\n")
    out.write("static constexpr size_t kKeyDeriveCount = "
              "sizeof(kKeyDeriveVecs) / sizeof(kKeyDeriveVecs[0]);\n\n")

    out.write("static const VerifyVec kVerifyVecs[] = {\n")
    for offs, accept in vf_table:
        qx_off, qy_off, h_off, r_off, s_off = offs
        out.write(f"    {{ kSecArena + {qx_off}, kSecArena + {qy_off}, "
                  f"kSecArena + {h_off}, kSecArena + {r_off}, "
                  f"kSecArena + {s_off}, {accept}u }},\n")
    out.write("};\n")
    out.write("static constexpr size_t kVerifyCount = "
              "sizeof(kVerifyVecs) / sizeof(kVerifyVecs[0]);\n\n")

    out.write("static const SignVec kSignVecs[] = {\n")
    for offs in sign_table:
        d_off, h_off, k_off, r_off, s_off = offs
        out.write(f"    {{ kSecArena + {d_off}, kSecArena + {h_off}, "
                  f"kSecArena + {k_off}, kSecArena + {r_off}, "
                  f"kSecArena + {s_off} }},\n")
    out.write("};\n")
    out.write("static constexpr size_t kSignCount = "
              "sizeof(kSignVecs) / sizeof(kSignVecs[0]);\n\n")

    return 0


# RFC 6979 deterministic nonce derivation (HMAC-SHA-256, secp256k1 n).
def rfc6979_k(privkey: int, msg_hash: int) -> int:
    n = SECP256K1_N
    qlen = n.bit_length()
    rolen = (qlen + 7) // 8
    h1 = msg_hash.to_bytes(32, "big") if msg_hash.bit_length() <= 256 else \
        (msg_hash & ((1 << 256) - 1)).to_bytes(32, "big")
    # bits2int + reduce mod n on the hash
    h_int = int.from_bytes(h1, "big")
    if h_int >= n:
        h_int -= n
    h1 = h_int.to_bytes(32, "big")

    x = privkey.to_bytes(rolen, "big")
    V = b"\x01" * 32
    K = b"\x00" * 32

    import hmac

    def H(k: bytes, m: bytes) -> bytes:
        return hmac.new(k, m, hashlib.sha256).digest()

    K = H(K, V + b"\x00" + x + h1)
    V = H(K, V)
    K = H(K, V + b"\x01" + x + h1)
    V = H(K, V)

    while True:
        T = b""
        while len(T) < rolen:
            V = H(K, V)
            T = T + V
        k = int.from_bytes(T[:rolen], "big")
        if 1 <= k < n:
            return k
        K = H(K, V + b"\x00")
        V = H(K, V)


def sign_with_explicit_k(d: int, h: int, k: int) -> tuple[int, int]:
    n = SECP256K1_N
    # R = k*G
    pk = coincurve.PrivateKey(k.to_bytes(32, "big"))
    pub = pk.public_key.format(compressed=False)
    rx = int.from_bytes(pub[1:33], "big")
    r = rx % n
    if r == 0:
        return 0, 0
    k_inv = pow(k, n - 2, n)
    s = (k_inv * (h + r * d)) % n
    if s == 0:
        return 0, 0
    return r, s


if __name__ == "__main__":
    sys.exit(main())
